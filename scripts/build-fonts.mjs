// 자체 호스팅 폰트: @fontsource에서 필요한 굵기만 site/public/fonts/로 복사 → 배포 시 /fonts/fonts.css
// 사이트와 학습앱(/app/)이 같은 파일을 공유한다.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fs = join(root, 'site/node_modules/@fontsource');
const out = join(root, 'site/public/fonts');
const PICK = [['hahmlet', [500, 700]], ['ibm-plex-sans-kr', [400, 600]]];

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'files'), { recursive: true });
let css = '/* generated by scripts/build-fonts.mjs */\n';
for (const [pkg, weights] of PICK) {
  for (const w of weights) {
    let src = readFileSync(join(fs, pkg, `${w}.css`), 'utf8');
    // woff 폴백은 빼고 woff2만 남긴다
    src = src.replace(/,\s*url\(\.\/files\/[^)]+\.woff\) format\('woff'\)/g, '');
    for (const m of src.matchAll(/url\(\.\/files\/([^)]+\.woff2)\)/g)) copyFileSync(join(fs, pkg, 'files', m[1]), join(out, 'files', m[1]));
    css += src + '\n';
  }
}
writeFileSync(join(out, 'fonts.css'), css);
console.log('✓ fonts →', out);
